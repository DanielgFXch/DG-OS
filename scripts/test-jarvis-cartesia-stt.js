#!/usr/bin/env node
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const src=read('supabase/functions/jarvis-private/index.ts');
const privateHub=read('private-hub.js');
const mobile=read('jarvis-microphone.js');
const html=read('index.html');
const sw=read('sw.js');
assert.ok(src.includes('const cartesiaKey = Deno.env.get("CARTESIA_API_KEY")'),
  'Reuse existing Cartesia secret without copying keys');
assert.ok(src.includes('if (!cartesiaKey && !openaiKey)'),'OpenAI optional; do not hard-require it');
assert.ok(src.includes('endpoint = "https://api.cartesia.ai/stt"'));
assert.ok(src.includes('upload.append("model", "ink-whisper")'),'Only this STT variant supports German');
assert.ok(src.includes('upload.append("language", "de")'),'Explicitly request German transcription');
assert.ok(src.includes('"Cartesia-Version": "2026-08-14"'),'Cartesia version must match active voice API');
assert.ok(src.includes('Authorization: "Bearer " + cartesiaKey'),'Use server-only Bearer token');
assert.ok(src.includes('providers.push("cartesia")'),'Preferred existing voice provider');
assert.ok(src.includes('providers.push("openai")'),'Optional OpenAI fallback');
assert.ok(src.indexOf('providers.push("cartesia")')<src.indexOf('providers.push("openai")'));
assert.ok(src.includes('await authorized(req)'),'Keep paired-device auth for STT');
assert.ok(src.includes('owner + ":audio"'),'Keep rate limit');
assert.ok(src.includes('file.size > 2_000_000'),'Keep size bound');
assert.ok(src.includes('AbortSignal.timeout(23000)'),'External calls must timeout');
assert.ok(src.includes('return json({ transcript, provider }, 200, origin)'));
assert.ok(src.includes('error: "stt_not_configured"'),'Explain both keys absent');
assert.ok(src.includes('error: "transcription_unavailable"'),'External provider errors must be reported');
assert.ok(!src.includes('console.log(result.text)'),'Never log transcripts');
assert.ok(mobile.includes("data.error==='stt_not_configured'"),'Provide provider-specific UI error');
assert.ok(mobile.includes("data.error==='transcription_unavailable'"),'Tell user when provider unavailable');
assert.ok(!mobile.includes('CARTESIA_API_KEY'),'Provider secrets never in frontend');
assert.ok(!privateHub.includes('CARTESIA_API_KEY'),'Provider secrets never in app bundle');
assert.ok(html.includes('jarvis-microphone.js?v=2'));
assert.ok(html.includes('personal.js?v=0.59.6'));
assert.ok(sw.includes('dgos-personal-shell-39'));
assert.ok(sw.includes('jarvis-microphone.js?v=2'));
assert.doesNotThrow(()=>new Function(mobile));
assert.doesNotThrow(()=>new Function(read('personal.js')));
console.log('German Cartesia STT fallback, security and iPhone deployment contract checks passed');
